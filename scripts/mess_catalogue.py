"""Render docs/mess-catalogue.md from the mess registry.

Run from the repository root: ``python scripts/mess_catalogue.py``. The output is generated from
the registered mess types and one example event per subtype, taken from a fixed dataset (the
``nightmare`` preset, 300 households, seed 42), so it is reproducible. A test regenerates it and
fails when the committed file is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

from onboardkit.datagen.config import resolve_config
from onboardkit.datagen.mess.base import DescribesSubtypes, MessEvent
from onboardkit.datagen.mess.registry import CANONICAL_ORDER, DEFAULT_REGISTRY
from onboardkit.datagen.pipeline import build_rows

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "mess-catalogue.md"
PRESET, SIZE, SEED = "nightmare", 300, 42


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _example(event: MessEvent) -> str:
    where = f"{event.source}.{event.table}"
    what = event.concept or "(several fields)"
    change = f"`{_cell(event.before)}` to `{_cell(event.after)}`"
    return f"{where}, {what}: {change}"


def render() -> str:
    built = build_rows(resolve_config(PRESET, SIZE, SEED))
    first: dict[tuple[str, str], MessEvent] = {}
    for event in built.mess_events:
        first.setdefault((event.mess_type, event.subtype), event)

    lines = [
        "# Mess catalogue",
        "",
        "Generated by `scripts/mess_catalogue.py` from the mess registry. Do not edit by hand.",
        f"Examples come from the `{PRESET}` preset with {SIZE} households and seed {SEED}.",
        "",
        "A mess type's *intensity* (0 to 1) times its *max rate* is the share of eligible rows it "
        "affects. Types run in this order: "
        + ", ".join(f"`{name}`" for name in CANONICAL_ORDER)
        + ".",
    ]
    for name in sorted(DEFAULT_REGISTRY.names(), key=CANONICAL_ORDER.index):
        mess = DEFAULT_REGISTRY.get(name)
        assert isinstance(mess, DescribesSubtypes)
        lines += [
            "",
            f"## {name}",
            "",
            mess.description,
            "",
            f"- Max rate: {mess.max_rate}",
            f"- Structural (may add or remove rows): {'yes' if mess.structural else 'no'}",
            "- Touched concepts: " + ", ".join(f"`{c}`" for c in sorted(mess.touches)),
            "",
            "| Subtype | Severity, ambiguity | Example |",
            "|---|---|---|",
        ]
        for subtype in sorted(mess.subtypes):
            event = first.get((name, subtype))
            if event is None:
                lines.append(f"| `{subtype}` | | no example in this dataset |")
                continue
            label = ", ".join(x for x in (event.severity, event.ambiguity) if x)
            lines.append(f"| `{subtype}` | {label} | {_example(event)} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
